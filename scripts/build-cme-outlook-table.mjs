#!/usr/bin/env node
/**
 * scripts/build-cme-outlook-table.mjs — bake js/cme-outlook-response.js.
 *
 * For every (launch lon, launch lat, v0) on a fixed grid, one synthetic CME
 * is seeded through `donkiToPreset` (EXACTLY the live DONKI seeding — same
 * spreads, same sheath, same defaults) and flown through the committed
 * flux-rope WASM ensemble. Per cell the table keeps:
 *
 *   h  P(hit at L1)
 *   g  P(min Bz < −10 nT at L1) — sheath included, so g CAN exceed h
 *      (a flank pass the rope misses still drags its sheath over L1)
 *   q  arrival-time quantiles [h after the 21.5 R☉ launch] of HITTING
 *      members at Q_LEVELS (null when fewer than MIN_HITS members hit)
 *
 * Why baked: ~33 ms per ensemble cell, ~1000 cells. The browser and the cron
 * both read the table; tests/cme-outlook.mjs recomputes sample cells against
 * the WASM so a kernel or seeding change fails the gate until this is re-run.
 *
 *   node scripts/build-cme-outlook-table.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { loadFluxRopeKernel } from '../js/flux-rope-kernel.js';
import { buildResponseCell, RESPONSE_GRID } from '../js/cme-outlook.js';

const root = new URL('../', import.meta.url);
const wasm = await readFile(fileURLToPath(new URL('js/flux-rope-wasm/flux_rope_core.wasm', root)));
const k = await loadFluxRopeKernel(wasm);

const { lonDeg, latDeg, v0Kms } = RESPONSE_GRID;
const cells = [];
const t0 = Date.now();
for (const lat of latDeg) {
    for (const lon of lonDeg) {
        for (const v of v0Kms) cells.push(buildResponseCell(k, { lonDeg: lon, latDeg: lat, v0Kms: v }));
    }
}
const body = `// GENERATED by scripts/build-cme-outlook-table.mjs — do not hand-edit.
// Flux-rope ensemble response of a synthetic DONKI-seeded CME on the grid
// RESPONSE_GRID (js/cme-outlook.js), cell order lat → lon → v0.
// Each cell: [h = P(rope hit), g = P(minBz < −10 nT, sheath included), q = arrival quantiles
// (h after launch) at RESPONSE_GRID.qLevels, or null].
// Re-bake after ANY flux-rope kernel or donkiToPreset change;
// tests/cme-outlook.mjs recomputes sample cells and fails on drift.
export const RESPONSE_CELLS = ${JSON.stringify(cells.map((c) => [c.h, c.g, c.q]))};
`;
await writeFile(fileURLToPath(new URL('js/cme-outlook-response.js', root)), body);
console.log(`baked ${cells.length} cells in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
