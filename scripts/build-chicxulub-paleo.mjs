#!/usr/bin/env node
/**
 * build-chicxulub-paleo.mjs — the Chicxulub sites at 66 Ma, from the plate
 * model, written as a small data module the page can import synchronously.
 *
 *     node scripts/build-chicxulub-paleo.mjs [--check]
 *
 * It computes nothing of its own: every number is js/paleo/rotations.js run
 * on data/paleo/ (Müller et al. 2019, baked by scripts/build-paleo-model.py).
 * --check fails if js/chicxulub/paleo-sites.js is not what this writes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as PR from '../js/paleo/rotations.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const AGE_MA = 66.04;                   // Renne et al. 2013, the age already in observations.js
const R_KM = 6371;
const rot = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/paleo/muller2019-rotations.json'), 'utf8'));
const { sites } = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/paleo/muller2019-sites.json'), 'utf8'));
const model = PR.createModel(rot);

const r4 = (x) => Math.round(x * 1e4) / 1e4;
const out = {};
const c = sites.chicxulub, c66 = model.reconstruct(c.lat, c.lon, c.plate, AGE_MA);
for (const [key, s] of Object.entries(sites)) {
    const p = model.reconstruct(s.lat, s.lon, s.plate, AGE_MA);
    out[key] = {
        plate: s.plate, plateName: s.name, plateRule: s.rule,
        today: { latDeg: s.lat, lonDeg: s.lon },
        at66: { latDeg: r4(p.lat), lonDeg: r4(p.lon) },
        chain: model.total(s.plate, AGE_MA).chain,
        distanceTodayKm: r4(PR.angularDistance(c.lat, c.lon, s.lat, s.lon) * Math.PI / 180 * R_KM),
        distance66Km: r4(PR.angularDistance(c66.lat, c66.lon, p.lat, p.lon) * Math.PI / 180 * R_KM),
    };
}
// a bearing measured today at the crater, turned by the plate's rotation
const bearings = [0, 45, 90, 135, 180, 225, 270, 315].map((b) => [b, r4(PR.reconstructBearing(model, c.lat, c.lon, b, c.plate, AGE_MA))]);
const shift = r4(((bearings[1][1] - 45) % 360 + 540) % 360 - 180);

const body = `/**
 * chicxulub/paleo-sites.js — GENERATED by scripts/build-chicxulub-paleo.mjs.
 * Do not edit; re-run the script (node tests/chicxulub.mjs fails when stale).
 *
 * Where the crater and the ejecta sites were ${AGE_MA} Myr ago, by the plate
 * model ${rot.meta.model} (${rot.meta.licence}), run through js/paleo/rotations.js.
 * Positions are in the model's MANTLE frame, not a palaeomagnetic one:
 * true polar wander (a few degrees since 66 Ma) is not in them.
 */
export const PALEO_AGE_MA = ${AGE_MA};
export const PALEO_MODEL = ${JSON.stringify({ model: rot.meta.model, licence: rot.meta.licence, frame: 'mantle (optimised absolute reference frame); not palaeomagnetic' })};
export const PALEO_SITES = Object.freeze(${JSON.stringify(out, null, 4)});
/** A bearing at the crater measured today → the same direction at ${AGE_MA} Ma. */
export const PALEO_BEARINGS = Object.freeze(${JSON.stringify(bearings)});
/** The turn of the crater's local compass since then (deg, + = clockwise). */
export const PALEO_BEARING_SHIFT_DEG = ${shift};
`;

const file = path.join(ROOT, 'js/chicxulub/paleo-sites.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body) { console.error('js/chicxulub/paleo-sites.js is stale'); process.exit(1); }
    console.log('chicxulub paleo sites: up to date');
} else {
    fs.writeFileSync(file, body);
    console.log(`wrote ${path.relative(ROOT, file)}: crater at ${AGE_MA} Ma ${out.chicxulub.at66.latDeg}°, ${out.chicxulub.at66.lonDeg}°; bearing shift ${shift}°`);
}
