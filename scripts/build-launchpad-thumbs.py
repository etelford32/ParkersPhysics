#!/usr/bin/env python3
"""
build-launchpad-thumbs.py — small posters for the homepage launchpad
════════════════════════════════════════════════════════════════════
The launchpad (index.html #hero, js/home-launchpad.js) is the FIRST SCREEN of
the homepage. The Simulation Showcase's posters are 1920 px captures of
150–290 KB each; nine of them above the fold would be ~2 MB before the visitor
has seen anything. This script derives two sizes from every poster listed in
assets/home/showcase/manifest.json:

    assets/home/launchpad/<id>-480.jpg    the "always live" tiles
    assets/home/launchpad/<id>-960.jpg    the carousel slides

and writes js/home-launchpad-media.js — the list of ids that HAVE a capture
and when it was taken — so the page knows, without a request, which
simulations get a photograph and which get the glyph plate. Nothing here
invents an image: a simulation with no capture has no thumbnail.

Run after scripts/capture-home-showcase.mjs:

    python3 scripts/build-launchpad-thumbs.py            # write
    python3 scripts/build-launchpad-thumbs.py --check    # fail if stale (CI / node gate)

--check compares the id list + capture dates in the module and the presence of
both files per id; it does not compare JPEG bytes (encoders differ by version).
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / 'assets/home/showcase/manifest.json'
OUT_DIR = ROOT / 'assets/home/launchpad'
MODULE = ROOT / 'js/home-launchpad-media.js'
WIDTHS = (480, 960)
ASPECT = 16 / 9          # both launchpad frames are 16:9; the captures are 16:9.6


def module_text(slides):
    rows = ',\n'.join(
        f"    {json.dumps(s['id'])}: {{ capturedAt: {json.dumps(s.get('capturedAt'))}, renderer: {json.dumps(s.get('renderer'))} }}"
        for s in slides)
    return (
        '/**\n'
        ' * home-launchpad-media.js — GENERATED by scripts/build-launchpad-thumbs.py.\n'
        ' * Do not hand-edit: re-run the script after a showcase capture.\n'
        ' * Which simulations have a launchpad thumbnail (assets/home/launchpad/<id>-480.jpg\n'
        ' * and -960.jpg), and when the capture it was cut from was taken.\n'
        ' */\n'
        "export const LAUNCHPAD_MEDIA_DIR = 'assets/home/launchpad/';\n"
        f'export const LAUNCHPAD_THUMB_WIDTHS = Object.freeze([{", ".join(map(str, WIDTHS))}]);\n'
        'export const LAUNCHPAD_MEDIA = Object.freeze({\n' + rows + '\n});\n')


def main():
    check = '--check' in sys.argv
    slides = [s for s in json.loads(MANIFEST.read_text())['slides'] if s.get('poster') and (ROOT / s['poster']).exists()]
    text = module_text(slides)
    if check:
        problems = []
        if not MODULE.exists() or MODULE.read_text() != text:
            problems.append(f'{MODULE.relative_to(ROOT)} is stale')
        for s in slides:
            for w in WIDTHS:
                f = OUT_DIR / f"{s['id']}-{w}.jpg"
                if not f.exists():
                    problems.append(f'missing {f.relative_to(ROOT)}')
        if problems:
            print('\n'.join('✗ ' + p for p in problems))
            print('run: python3 scripts/build-launchpad-thumbs.py')
            sys.exit(1)
        print(f'✓ launchpad thumbnails current ({len(slides)} simulations × {len(WIDTHS)} sizes)')
        return
    from PIL import Image          # write mode only: --check runs on the standard library (CI has no Pillow)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    total = 0
    for s in slides:
        im = Image.open(ROOT / s['poster']).convert('RGB')
        w, h = im.size
        th = round(w / ASPECT)                    # centre-crop to 16:9
        if th < h:
            top = (h - th) // 2
            im = im.crop((0, top, w, top + th))
        for tw in WIDTHS:
            out = OUT_DIR / f"{s['id']}-{tw}.jpg"
            im.resize((tw, round(tw / ASPECT)), Image.LANCZOS).save(out, 'JPEG', quality=80, optimize=True, progressive=True)
            total += out.stat().st_size
    MODULE.write_text(text)
    print(f'wrote {len(slides) * len(WIDTHS)} thumbnails ({total / 1024:.0f} KB) + {MODULE.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
