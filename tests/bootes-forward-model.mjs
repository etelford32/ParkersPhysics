#!/usr/bin/env node
/**
 * bootes-forward-model.mjs — gate for js/bootes-forward-model.js, the
 * Bayesian forward-model fit of the reconstruction's initial field
 * (BOOTES_VOID_PLAN.md §4l).
 *
 * Run: node tests/bootes-forward-model.mjs        (~1 min)
 *
 *   1. THE DATA: seeded points inside the sphere; the field is LINEAR in its
 *      sources (two trees add to the field of their union).
 *   2. THE PRIOR's band: W*s keeps constants and linear fields exactly in
 *      the interior, passes λ = 200 Mpc, and removes the element scale.
 *   3. IDENTITY: started AT the truth (data generated by the same forward
 *      model) the fit stops at once on the noise, s₁ untouched to the bit.
 *   4. RECOVERY: a planted, band-limited, curl-free change to the initial
 *      field is recovered from today's field alone — the data misfit falls
 *      at every accepted step and the recovered change correlates with the
 *      planted one at the elements' resolution.
 */

import assert from 'node:assert/strict';

import { meanMatterDensityMsunMpc3 } from '../js/bootes-void-model.js';
import { mulberry32 } from '../js/bootes-web-model.js';
import { voidRedshift } from '../js/bootes-void-data.js';
import * as NB from '../js/bootes-nbody.js';
import * as RC from '../js/bootes-reconstruct.js';
import * as FM from '../js/bootes-forward-model.js';
import { lptGrowth, secondOrderDisplacement } from '../js/bootes-lpt.js';
import * as SG from '../js/bootes-softgrowth.js';

let passed = 0;
const ok = (name) => { console.log(`  ✓ ${name}`); passed++; };

const A_OBS = 1 / (1 + voidRedshift());
const A_INIT = 0.1;
const rho = meanMatterDensityMsunMpc3();
const SIM = NB.PAGE_CONFIG.sim;
const R = 110, SPACING = 14, H = 2 * SPACING;
const glass = RC.buildGlass({ radius: R, spacing: SPACING, refineRadius: Infinity, seed: 5, ...SIM });
const vol = Float64Array.from(glass.mass, (m) => m / rho);
const hs = Float64Array.from(glass.mass, () => H);
const radiusOf = (P, i) => Math.hypot(P[3 * i], P[3 * i + 1], P[3 * i + 2]);

// ── 1. The data ─────────────────────────────────────────────────────────────
const points = FM.dataPoints({ radius: R, n: 3000, seed: 7 });
{
    const again = FM.dataPoints({ radius: R, n: 3000, seed: 7 });
    let inside = true;
    for (let i = 0; i < 3000; i++) inside &&= radiusOf(points, i) < 0.95 * R;
    assert.ok(inside && again.every((v, k) => v === points[k]), 'points: inside and seeded');
    // Linearity: the field of the whole glass = the two halves' fields summed.
    const idx = [[], []];
    for (let i = 0; i < glass.n; i++) idx[i % 2].push(i);
    const whole = FM.fieldAtPoints({ sources: [{ pos: glass.pos, mass: glass.mass, softening: glass.softening }],
        radius: R, points, meanSoftening: glass.softening, theta: 1e-3, ...{ leafSize: 16 } });
    const halves = FM.fieldAtPoints({ sources: idx.map((ix) => ({ pos: glass.pos, mass: glass.mass, softening: glass.softening,
        index: Int32Array.from(ix) })), radius: R, points, meanSoftening: glass.softening, theta: 1e-3, leafSize: 16 });
    let worst = 0;
    for (let k = 0; k < whole.length; k++) worst = Math.max(worst, Math.abs(whole[k] - halves[k]));
    assert.ok(worst < 1e-6 * FM.rmsVector(whole) + 1e-9, `linearity ${worst}`);
    ok(`the data: 3000 seeded points inside 0.95 R; the field is linear in its sources (two trees add to their union to ${worst.toExponential(1)})`);
}

// ── 2. The prior's band ─────────────────────────────────────────────────────
const band = FM.bandKernel({ h: H, kappa: 5 });
// The band as the fit applies it: s + ∫W(s′ − s) = W*s (difference form).
const deconvolveBand = (s) => SG.deconvolveGrowth(glass.pos, s, vol, band);
const INTERIOR = R - 30;   // the band is ~h/κ wide; its rim continuation is not the claim here
{
    let integral = 0;
    band.K.forEach((v, j) => { integral += v * 4 * Math.PI * (j * band.dr) ** 2 * band.dr; });
    const meas = (s) => {
        const out = deconvolveBand(s);
        let e = 0, t = 0;
        for (let i = 0; i < glass.n; i++) {
            if (radiusOf(glass.pos, i) > INTERIOR) continue;
            for (let d = 0; d < 3; d++) { e += (out[3 * i + d] - s[3 * i + d]) ** 2; t += s[3 * i + d] ** 2; }
        }
        return Math.sqrt(e / t);
    };
    const lin = new Float64Array(3 * glass.n);
    for (let i = 0; i < glass.n; i++) { lin[3 * i] = 0.3 + 0.01 * glass.pos[3 * i + 1]; lin[3 * i + 1] = -0.02 * glass.pos[3 * i + 2]; }
    const wave = (lam) => {
        const s = new Float64Array(3 * glass.n);
        for (let i = 0; i < glass.n; i++) s[3 * i] = Math.sin(2 * Math.PI / lam * glass.pos[3 * i] + 0.4);
        return s;
    };
    const linErr = meas(lin), long = meas(wave(200));
    const kept = (() => {
        const s = wave(2 * SPACING), out = deconvolveBand(s);
        let a = 0, b = 0;
        for (let i = 0; i < glass.n; i++) {
            if (radiusOf(glass.pos, i) > INTERIOR) continue;
            a += out[3 * i] ** 2; b += s[3 * i] ** 2;
        }
        return Math.sqrt(a / b);
    })();
    if (process.env.DEBUG) console.log({ integral, linErr, long, kept });
    assert.ok(Math.abs(integral - 1) < 2e-3 && linErr < 0.02 && long < 0.05 && kept < 0.25,
        `band: ∫W ${integral}, linear ${linErr}, λ=200 ${long}, λ=2Δ ${kept}`);
    ok(`the prior's band (κ = 5): ∫W = ${integral.toFixed(4)}; a linear field passes to ${(100 * linErr).toFixed(1)} %, `
        + `λ = 200 Mpc to ${(100 * long).toFixed(1)} %, and the element scale (λ = ${2 * SPACING} Mpc) keeps ${(100 * kept).toFixed(0)} %`);
}

// ── 3–4. The fit ────────────────────────────────────────────────────────────
// A smooth "observed" initial field and a planted band-limited change to it,
// both curl-free (gradients of windowed sums of plane waves).
function potentialField(seed, amp, lamMin, lamMax) {
    const rng = mulberry32(seed);
    const waves = [];
    for (let i = 0; i < 8; i++) {
        const u = 2 * rng() - 1, ph = 2 * Math.PI * rng(), s = Math.sqrt(1 - u * u);
        const k = 2 * Math.PI / (lamMin + (lamMax - lamMin) * rng());
        waves.push({ kx: k * s * Math.cos(ph), ky: k * s * Math.sin(ph), kz: k * u, ph: 2 * Math.PI * rng(), A: 1 / k });
    }
    const W = (r) => { const x = r / (0.85 * R); return x >= 1 ? 0 : (1 - x * x) ** 3; };
    const pot = (x, y, z) => waves.reduce((a, w) => a + w.A * Math.cos(w.kx * x + w.ky * y + w.kz * z + w.ph), 0) * W(Math.hypot(x, y, z));
    const out = new Float64Array(3 * glass.n);
    const e = 1e-3;
    for (let i = 0; i < glass.n; i++) {
        const [x, y, z] = [glass.pos[3 * i], glass.pos[3 * i + 1], glass.pos[3 * i + 2]];
        out[3 * i] = -(pot(x + e, y, z) - pot(x - e, y, z)) / (2 * e);
        out[3 * i + 1] = -(pot(x, y + e, z) - pot(x, y - e, z)) / (2 * e);
        out[3 * i + 2] = -(pot(x, y, z + e) - pot(x, y, z - e)) / (2 * e);
    }
    const rms = FM.rmsVector(out);
    for (let k = 0; k < out.length; k++) out[k] *= amp / rms;
    return out;
}
const s1Base = potentialField(11, 2.0, 80, 200);
const delta = potentialField(23, 0.6, 90, 180);
const s1True = s1Base.map((v, k) => v + delta[k]);
const growth = lptGrowth(A_INIT, A_OBS);
const s2Of = (s) => secondOrderDisplacement(glass.pos, s, { volume: vol, hsoft: hs, h: H, ...SIM });
const CONFIG = { ...RC.RECON_CONFIG.forwardModel, maxIterations: 4 };
const truth = FM.forwardRun({ glass, s1: s1True, s2: s2Of(s1True), aInit: A_INIT, aObs: A_OBS, steps: CONFIG.innerSteps, points, growth, sim: SIM });
const data = { points, field: truth.field };
const tiny = 1e-3 * FM.rmsVector(truth.field);

{
    const fit = FM.forwardModelFit({ glass, s1: s1True, aInit: A_INIT, aObs: A_OBS, data, noise: tiny, config: CONFIG, sim: SIM });
    assert.ok(fit.stoppedBy === 'noise' && fit.history.length === 1 && fit.chi2 === 0
        && fit.s1.every((v, k) => v === s1True[k]), `identity: ${fit.stoppedBy} after ${fit.history.length - 1}, χ² ${fit.chi2}`);
    ok('identity: started at the truth the fit stops at once on the noise (χ² = 0), s₁ untouched to the bit');
}

{
    const t0 = Date.now();
    const fit = FM.forwardModelFit({ glass, s1: s1Base, aInit: A_INIT, aObs: A_OBS, data, noise: tiny, config: CONFIG, sim: SIM });
    const m = fit.history.map((h) => h.misfit);
    for (let i = 1; i < m.length; i++) assert.ok(m[i] < m[i - 1], `misfit must fall: ${m}`);
    // The recovered change vs the planted one, inside 0.7 R, both band-limited
    // (the fit claims the band, not the grain).
    const got = deconvolveBand(fit.s1.map((v, k) => v - s1Base[k])), want = deconvolveBand(delta);
    let e = 0, t = 0, g = 0, dot = 0;
    for (let i = 0; i < glass.n; i++) {
        if (radiusOf(glass.pos, i) > 0.7 * R) continue;
        for (let d = 0; d < 3; d++) {
            const u = got[3 * i + d], v = want[3 * i + d];
            e += (u - v) ** 2; t += v * v; g += u * u; dot += u * v;
        }
    }
    const rel = Math.sqrt(e / t), corr = dot / Math.sqrt(t * g), amp = Math.sqrt(g / t);
    if (process.env.DEBUG) console.log({ m, rel, corr, amp, gains: fit.history.map((h) => h.gain), s: (Date.now() - t0) / 1000 });
    assert.ok(m[m.length - 1] < 0.25 * m[0] && corr > 0.95 && rel < 0.3 && amp > 0.8, `recovery: misfit ${m}, rel ${rel}, corr ${corr}, amp ${amp}`);
    ok(`recovery: a planted change to the initial field (0.6 Mpc rms, λ 90–180 Mpc) is recovered from today's field alone — `
        + `misfit ${(100 * m[0]).toFixed(1)} → ${(100 * m[m.length - 1]).toFixed(1)} % over ${m.length - 1} steps (gains `
        + `${fit.history.slice(1).map((h) => h.gain).join(', ')}), the recovered change ${(100 * rel).toFixed(0)} % off the planted one `
        + `at the elements' resolution (correlation ${corr.toFixed(3)}, amplitude ${amp.toFixed(2)})`);
}

console.log(`\n${passed} checks passed — js/bootes-forward-model.js`);
